# ---------------------------------------------------------------- loading
def load_daily():
    """Daily sales of the online shop + London weather, one row per day WITH sales.

    The same table as `load_sales_weather()` last week (sales cleaned with our retail_tools),
    saved as a small CSV, plus one new column `day_number`.

    Returns:
        pd.DataFrame indexed by date (1 Dec 2010 - 9 Dec 2011, 305 rows) with the columns
        revenue, orders, customers, units, temp_mean, temp_max, temp_min, rain_mm, snow_cm,
        sunshine_h, wind_kmh, weekday ("Monday"...), month (1-12),
        day_number (days since 1 Dec 2010: 0, 1, 2, ...)
    """
    daily = pd.read_csv(DATA / "daily_sales_weather.csv", index_col="date", parse_dates=["date"])
    daily["day_number"] = (daily.index - pd.Timestamp("2010-12-01")).days
    return daily


def load_customers():
    """One row per customer (with a CustomerID) who bought something between 1 Dec 2010 and 31 Aug 2011.

    Returns:
        pd.DataFrame indexed by CustomerID with the columns
        country, orders (number of invoices), revenue (GBP), avg_order (GBP per invoice),
        products (number of different products), recency_days (days from the last purchase to 1 Sep 2011),
        tenure_days (days from the first purchase to 1 Sep 2011), first_purchase, last_purchase,
        returned (1 = bought again between 1 Sep and 9 Dec 2011, 0 = did not)
    """
    return pd.read_csv(DATA / "customers.csv", index_col="CustomerID")


def load_products():
    """One row per product (stock codes that start with a digit, sold on at least 10 invoices).

    Returns:
        pd.DataFrame indexed by StockCode with the columns
        description, avg_price (revenue / units, GBP), units (pieces sold in the whole year),
        revenue, invoices, customers, countries, median_qty (typical number of pieces per order line)
    """
    return pd.read_csv(DATA / "products.csv", index_col="StockCode")


def time_split(data, last_train_day="2011-09-30"):
    """Split a table with a date index BY TIME: train = up to last_train_day, test = the days after it.

    Returns:
        (train, test) - two DataFrames
    """
    train = data.loc[:last_train_day]
    test = data.loc[data.index > pd.Timestamp(last_train_day)]
    return train, test


def weekday_dummies(data):
    """Turn the `weekday` column into 0/1 columns Tuesday, Wednesday, Thursday, Friday, Sunday.

    Monday is the reference day (all five columns 0). There is no Saturday column: the shop never
    sells on Saturdays. Unlike pd.get_dummies(), the columns are ALWAYS the same - also for a
    table with one single day (warm-up Q3!), so a model trained on them can predict any day.
    """
    columns = ["Tuesday", "Wednesday", "Thursday", "Friday", "Sunday"]
    return pd.DataFrame({day: (data["weekday"] == day).astype(int) for day in columns}, index=data.index)


# ---------------------------------------------------------------- the parent class
class Analysis:
    """Parent class for every group's analysis (works like scikit-learn: create -> fit -> use).

    Your class inherits from it:

        class RainTest(Analysis):
            required_columns = ["revenue", "rain_mm"]
            def fit(self):
                ...                       # compute something from self.data
                self.results_ = ...       # store the result
                return self

    What you get for free:
        self.data        - a COPY of the DataFrame you passed in (safe to change)
        self.results_    - None until fit() stores something there
        check_fitted()   - raises RuntimeError if fit() was not called yet
        print(obj)       - shows e.g. RainTest(305 rows, fitted)
    """
    required_columns = []

    def __init__(self, data):
        if not isinstance(data, pd.DataFrame):
            raise TypeError("data must be a pandas DataFrame")
        missing = [c for c in self.required_columns if c not in data.columns]
        if missing:
            raise ValueError(f"data is missing the columns {missing}")
        self.data = data.copy()
        self.results_ = None

    def fit(self):
        raise NotImplementedError("every group writes its own fit() method")

    def check_fitted(self):
        if self.results_ is None:
            raise RuntimeError(f"call .fit() first - {type(self).__name__} is not fitted yet")

    def __repr__(self):
        status = "fitted" if self.results_ is not None else "not fitted"
        return f"{type(self).__name__}({len(self.data)} rows, {status})"


# ---------------------------------------------------------------- testing helper
def expect_error(func, *args, error=ValueError, **kwargs):
    """Return True if func(*args, **kwargs) raises `error`; otherwise raise AssertionError.

    Usage in tests:
        assert expect_error(RainTest, "not a dataframe", error=TypeError)
        assert expect_error(model.probability, orders=-1, recency_days=10)
    """
    try:
        func(*args, **kwargs)
    except error:
        return True
    raise AssertionError(f"{getattr(func, '__name__', func)} did NOT raise {error.__name__}")


# ---------------------------------------------------------------- website preview from a notebook
_preview = {"process": None}


def preview(page="app.py", port=8501):
    """Start a Streamlit page in the background and open it in your browser.

    The notebook stays free - you can keep running cells. Every time you SAVE the page file
    (or re-run its %%writefile cell), click "Rerun" in the browser (or press R there).

        preview("my_first_page.py")     # one single page
        preview()                       # the whole class website (app.py) with all group pages

    Stop it with stop_preview().
    """
    stop_preview(quiet=True)
    path = ROOT / page
    if not path.exists():
        raise FileNotFoundError(f"{path} does not exist - did you run the %%writefile cell?")
    command = [sys.executable, "-m", "streamlit", "run", str(path),
               "--server.port", str(port),
               "--server.headless", "true",               # don't ask for an e-mail, don't wait for input
               "--browser.gatherUsageStats", "false"]
    _preview["process"] = subprocess.Popen(command, cwd=ROOT)
    url = f"http://localhost:{port}"
    time.sleep(4)                                          # give the server a moment to start
    if _preview["process"].poll() is not None:             # it stopped already = something is wrong
        raise RuntimeError("Streamlit did not start. Is it installed?  ->  %pip install streamlit")
    if not os.environ.get("ML_BASE_NO_BROWSER"):           # (set only when notebooks are tested automatically)
        webbrowser.open(url)
    print(f"✅ {page} is running at {url}  (stop it with stop_preview())")


def stop_preview(quiet=False):
    """Stop the page started with preview()."""
    process = _preview["process"]
    if process is not None and process.poll() is None:
        process.terminate()
        process.wait(timeout=10)
        if not quiet:
            print("⏹️ preview stopped")
    _preview["process"] = None
